const { contextBridge, ipcRenderer } = require('electron');
const on = (name, cb) => { const listener = (_event, value) => cb(value); ipcRenderer.on(name, listener); return () => ipcRenderer.removeListener(name, listener); };
contextBridge.exposeInMainWorld('floatingAPI', {
  packsGet:()=>ipcRenderer.invoke('packs:get'),
  packsCommand:p=>ipcRenderer.invoke('packs:command',p),
  packsSelect:id=>ipcRenderer.invoke('packs:select',id),
  packsImport:()=>ipcRenderer.invoke('packs:import'),
  packsOpen:id=>ipcRenderer.invoke('packs:open',id),
  packsCompose:p=>ipcRenderer.invoke('packs:compose',p),
  packsCopy:p=>ipcRenderer.invoke('packs:copy',p),
  packsGenerate:p=>ipcRenderer.invoke('packs:generate',p),
  packsCancel:()=>ipcRenderer.invoke('packs:cancel'),
  packsConfig:()=>ipcRenderer.invoke('packs:config'),
  onPacksSelect:cb=>on('packs:select',cb),
  onPacksChanged:cb=>on('packs:changed',cb),
  listCredentials:()=>ipcRenderer.invoke('credentials:list'),
  getCredential:id=>ipcRenderer.invoke('credentials:get',id),
  saveCredential:p=>ipcRenderer.invoke('credentials:save',p),
  deleteCredentials:ids=>ipcRenderer.invoke('credentials:delete-many',ids),
  copyCredential:(id,field)=>ipcRenderer.invoke('credentials:copy',{id,field}),
  openCredential:id=>ipcRenderer.invoke('credentials:open',id),
  referenceGet:()=>ipcRenderer.invoke('reference:get'),
  referenceImage:id=>ipcRenderer.invoke('reference:image',id),
  referenceChoose:()=>ipcRenderer.invoke('reference:choose'),
  referenceImport:data=>ipcRenderer.invoke('reference:import',data),
  listWindows:()=>ipcRenderer.invoke('windows:list'),
  windowGroupsGet:()=>ipcRenderer.invoke('window-groups:get'),
  windowGroupsCommand:c=>ipcRenderer.invoke('window-groups:command',c),
  focusWindow:id=>ipcRenderer.invoke('windows:focus',id),
  toolGroupsGet:()=>ipcRenderer.invoke('window-tools:get'),
  toolGroupsCommand:c=>ipcRenderer.invoke('window-tools:command',c),
  linkSettings: changes=>ipcRenderer.invoke('links:settings',changes),
  linkImage: ref=>ipcRenderer.invoke('links:image',ref),
  linkAI: input=>ipcRenderer.invoke('links:ai',input),
  linkCancel: ()=>ipcRenderer.invoke('links:cancel'),
  plannerGet:()=>ipcRenderer.invoke('planner:get'),
  timerGet:()=>ipcRenderer.invoke('timer:get'),
  timerCommand:c=>ipcRenderer.invoke('timer:command',c),
  timerStartPlan:id=>ipcRenderer.invoke('timer:plan',id),
  plannerLegacy:()=>ipcRenderer.invoke('planner:legacy'),
  plannerCommand:c=>ipcRenderer.invoke('planner:command',c),
  plannerSuggest:input=>ipcRenderer.invoke('planner:suggest',input),
  plannerCancel:()=>ipcRenderer.invoke('planner:cancel'),
  plannerVoice:action=>ipcRenderer.invoke('planner:voice',action),
  request: (payload) => ipcRenderer.invoke('floats:request', payload),
  dock: () => ipcRenderer.invoke('floats:dock'),
  drag: (phase) => ipcRenderer.invoke('floats:drag', phase),
  prepare: (text) => ipcRenderer.invoke('meeting:prepare', text),
  cancel: () => ipcRenderer.invoke('meeting:cancel'),
  config: () => ipcRenderer.invoke('meeting:config'),
  importFiles: () => ipcRenderer.invoke('meeting:import'),
  copy: (text) => ipcRenderer.invoke('meeting:copy', text),
  onChanged: (cb) => on('floats:changed', cb),
  onClose: (cb) => on('floats:close-request', cb),
});
